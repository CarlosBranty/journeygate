//! `openhands`: the OpenHands Software Agent SDK (MIT), driven by a small
//! Python driver that speaks the `/task` file contract natively.
//!
//! Admission: **provisional** (architecture section 16: "A confirmar en el
//! adaptador antes de admitirlo"). The SDK is not installed on the dev machine
//! and the driver has only been checked to parse as Python; the pinned SDK
//! version, class paths and the stats API below must be confirmed against the
//! version baked into the image before the runtime is admitted.
//!
//! Sources (checked 2026-11-01, `OpenHands/software-agent-sdk` main via
//! context7):
//! - `LLM(usage_id=..., model=..., api_key=SecretStr(...))`,
//!   `Conversation(agent=..., workspace=...)`, `send_message`, `run`
//!   (openhands-workspace `TESTING.md`).
//! - `LLMSummarizingCondenser(llm, max_size, keep_first)` in
//!   `openhands/sdk/context/condenser/llm_summarizing_condenser.py`;
//!   `default_condenser` uses `max_size=80, keep_first=4`.
//! - The condenser gets its **own `usage_id`** (`condenser`, tokens.md and
//!   architecture 19.4) through `llm.model_copy(update={"usage_id": ...})`,
//!   so its spend is reported separately (one `model_call` per usage id).
//!   Unverified: the attribute names of the per-usage-id stats
//!   (`conversation_stats.usage_to_metrics[...]`, `accumulated_cost`,
//!   `accumulated_token_usage.{prompt_tokens, completion_tokens,
//!   cache_read_tokens, cache_write_tokens}`), and the event class names the
//!   callback maps (`ObservationEvent`, `AgentErrorEvent`, `MessageEvent`).
//!
//! Pinning: the SDK calls models through LiteLLM, so the model is
//! `litellm_proxy/<model>` with `base_url` = the gateway root and the key read
//! from `os.environ[key_env]`. The prompt arrives on stdin.

