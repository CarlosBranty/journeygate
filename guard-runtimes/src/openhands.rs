pub const NAME: &str = "openhands";
pub const DRIVER_PATH: &str = "/task/openhands/driver.py";
pub const CONFIG_PATH: &str = "/task/openhands/config.json";
pub const AGENT_USAGE_ID: &str = "agent";
pub const CONDENSER_USAGE_ID: &str = "condenser";

/// The driver run as `python3 driver.py config.json < prompt`.
pub const DRIVER_PY: &str = r##"#!/usr/bin/env python3
"""guard OpenHands driver (provisional): runs one task with the OpenHands SDK
and writes the /task file contract (docs/contracts/agent-task.md).

Generated by guard-runtimes; do not edit. argv[1] = config.json, stdin = prompt.
"""
import json
import os
import sys
from datetime import datetime, timezone


def now():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"


def clip(text, limit=2000):
    return text.encode("utf-8")[:limit].decode("utf-8", "ignore")


class Events:
    def __init__(self, path):
        self.file = open(path, "w", encoding="utf-8")
        self.seq = 0

    def emit(self, kind, **fields):
        self.seq += 1
        record = {"seq": self.seq, "ts": now(), "kind": kind}
        record.update(fields)
        self.file.write(json.dumps(record, separators=(",", ":")) + "\n")
        self.file.flush()


def usage_of(metrics):
    tokens = getattr(metrics, "accumulated_token_usage", None)
    return {
        "input_tokens": int(getattr(tokens, "prompt_tokens", 0) or 0),
        "output_tokens": int(getattr(tokens, "completion_tokens", 0) or 0),
        "cached_input_tokens": int(getattr(tokens, "cache_read_tokens", 0) or 0),
        "cache_creation_input_tokens": int(getattr(tokens, "cache_write_tokens", 0) or 0),
    }


def main():
    with open(sys.argv[1], encoding="utf-8") as fh:
        cfg = json.load(fh)
    prompt = sys.stdin.read()
    events = Events(cfg["events_file"])
    zero = {"input_tokens": 0, "output_tokens": 0, "cached_input_tokens": 0, "cache_creation_input_tokens": 0}
    result = {"version": cfg["version"], "status": "failed", "summary": "", "usage": dict(zero),
              "cost_usd": 0.0, "steps": 0, "memory_proposals": []}
    last = {"text": "", "steps": 0}
    try:
        from pydantic import SecretStr
        from openhands.sdk import LLM, Agent, Conversation, Tool
        from openhands.sdk.context.condenser import LLMSummarizingCondenser
        from openhands.tools.file_editor import FileEditorTool
        from openhands.tools.terminal import TerminalTool

        llm = LLM(
            model=cfg["model"],
            base_url=cfg["base_url"],
            api_key=SecretStr(os.environ[cfg["key_env"]]),
            usage_id=cfg["agent_usage_id"],
        )
        condenser = LLMSummarizingCondenser(
            llm=llm.model_copy(update={"usage_id": cfg["condenser"]["usage_id"]}),
            max_size=cfg["condenser"]["max_size"],
            keep_first=cfg["condenser"]["keep_first"],
        )
        agent = Agent(
            llm=llm,
            tools=[Tool(name=TerminalTool.name), Tool(name=FileEditorTool.name)],
            condenser=condenser,
        )

        def on_event(event):
            name = type(event).__name__
            if name in ("ObservationEvent", "AgentErrorEvent"):
                last["steps"] += 1
                events.emit("tool_call", tool=str(getattr(event, "tool_name", "unknown")),
                            ok=name == "ObservationEvent", duration_ms=0)
            elif name == "MessageEvent" and str(getattr(event, "source", "")) == "agent":
                message = getattr(event, "llm_message", None)
                text = "".join(str(getattr(c, "text", "")) for c in getattr(message, "content", []) or [])
                if text.strip():
                    last["text"] = text
                    events.emit("message", text=clip(text))

        conversation = Conversation(agent=agent, workspace=cfg["workspace"], callbacks=[on_event],
                                    max_iteration_per_run=cfg["max_iterations"])
        conversation.send_message(prompt)
        conversation.run()

        total = dict(zero)
        cost = 0.0
        per_usage = getattr(conversation.conversation_stats, "usage_to_metrics", {}) or {}
        for usage_id in (cfg["agent_usage_id"], cfg["condenser"]["usage_id"]):
            metrics = per_usage.get(usage_id)
            if metrics is None:
                continue
            usage = usage_of(metrics)
            spent = float(getattr(metrics, "accumulated_cost", 0.0) or 0.0)
            events.emit("model_call", model=cfg["model_name"], usage=usage, cost_usd=spent)
            for key in total:
                total[key] += usage[key]
            cost += spent
        result.update(usage=total, cost_usd=cost, steps=last["steps"], summary=clip(last["text"], 4000))
        result["status"] = "budget_exceeded" if cost > cfg["max_budget_usd"] else "completed"
        if result["status"] != "completed":
            result["error"] = "budget exceeded"
    except Exception as exc:  # the orchestrator reads the reason from result.json
        events.emit("error", message=clip(f"{type(exc).__name__}: {exc}"))
        result["error"] = clip(f"{type(exc).__name__}: {exc}")
    with open(cfg["result_file"], "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2)
        fh.write("\n")
    return 0 if result["status"] == "completed" else 1


if __name__ == "__main__":
    sys.exit(main())
"##;

pub fn invocation(task: &AgentTask) -> Result<Invocation, RuntimeError> {
    let ep = GatewayEndpoint::pin(&task.gateway)?;
    let config = json!({
        "version": TASK_SCHEMA_VERSION,
        "model": format!("litellm_proxy/{}", task.model),
        "model_name": task.model,
        "base_url": ep.root(),
        "key_env": task.gateway.key_env,
        "agent_usage_id": AGENT_USAGE_ID,
        "condenser": { "usage_id": CONDENSER_USAGE_ID, "max_size": 80, "keep_first": 4 },
        "workspace": WORKSPACE_DIR,
        "max_iterations": 100,
        "max_budget_usd": task.budget_usd,
        "events_file": EVENTS_FILE,
        "result_file": RESULT_FILE,
    });
    let mut cfg = serde_json::to_string_pretty(&config).expect("json");
    cfg.push('\n');
    let mut inv = Invocation::new(vec![
        "python3".into(),
        DRIVER_PATH.into(),
        CONFIG_PATH.into(),
    ])
    .with_env("PYTHONDONTWRITEBYTECODE", "1")
    .with_env("PYTHONUNBUFFERED", "1")
    .with_file(DRIVER_PATH, DRIVER_PY)
    .with_file(CONFIG_PATH, cfg);
    inv.stdin = Some(prompt::render(task));
    Ok(inv)
}

process_runtime!(
    /// `AgentRuntime` for the OpenHands SDK (provisional).
    OpenHandsRuntime
);

#[async_trait::async_trait]
impl ProcessAdapter for OpenHandsRuntime {
    fn name(&self) -> &'static str {
        NAME
    }

    fn invocation(&self, task: &AgentTask) -> Result<Invocation, RuntimeError> {
        invocation(task)
    }

    fn writes_contract_files(&self) -> bool {
        true
    }

    async fn collect(
        &self,
        provider: &dyn SandboxProvider,
        sandbox: &Sandbox,
        _task: &AgentTask,
        _output: &ExecOutput,
        _clock: &dyn Clock,
    ) -> Result<Parsed, RuntimeError> {
        let read = |path: &'static str| async move {
            match provider.read_file(sandbox, path).await {
                Ok(b) => Ok(b),
                Err(SandboxError::NotFound(_)) => {
                    Err(RuntimeError::Protocol(format!("openhands wrote no {path}")))
                }
                Err(e) => Err(RuntimeError::from(e)),
            }
        };
        let events = from_jsonl(&read(EVENTS_FILE).await?).map_err(RuntimeError::Protocol)?;
        let result: TaskResult = serde_json::from_slice(&read(RESULT_FILE).await?)
            .map_err(|e| RuntimeError::Protocol(format!("result.json: {e}")))?;
        if result.version != TASK_SCHEMA_VERSION {
            return Err(RuntimeError::Protocol(format!(
                "result.json version {} is not {TASK_SCHEMA_VERSION}",
                result.version
            )));
        }
        Ok(Parsed {
            events,
            result: Some(result),
        })
    }
}
