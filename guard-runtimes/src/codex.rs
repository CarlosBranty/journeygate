//! `codex`: Codex CLI in exec mode (`codex exec --json`).
//!
//! Sources (checked 2026-11-01; installed CLI `codex exec --help`, 0.159.2;
//! `openai/codex` tag `rust-v0.155.1` for the config schema and SDK types):
//! - Flags `--json` ("Print events to stdout as JSONL"), `--ephemeral`,
//!   `--skip-git-repo-check`, `-C/--cd`, prompt `-` = read stdin:
//!   `codex exec --help`.
//! - `config.toml` keys and enums from `codex-rs/core/config.schema.json`:
//!   `model_provider`, `model_providers.<id>.{name, base_url, env_key,
//!   wire_api = "responses"}` (the only `WireApi`), `approval_policy = "never"`,
//!   `sandbox_mode` (`read-only` | `workspace-write` | `danger-full-access`),
//!   `sandbox_workspace_write.{writable_roots, network_access}`,
//!   `web_search = "disabled"`, `check_for_update_on_startup`,
//!   `analytics.enabled`, `feedback.enabled`, `history.persistence = "none"`,
//!   `shell_environment_policy.inherit = "core"`,
//!   `mcp_servers.<id>.{command, args, enabled_tools}`.
//!   `CODEX_HOME` points Codex at `/task/codex` (`--ignore-user-config` help:
//!   "Do not load `$CODEX_HOME/config.toml`").
//! - Event stream (`sdk/typescript/src/events.ts`, `items.ts`):
//!   `thread.started`, `turn.started`, `turn.completed {usage: {input_tokens,
//!   cached_input_tokens, cache_write_input_tokens, output_tokens,
//!   reasoning_output_tokens}}`, `turn.failed {error.message}`,
//!   `item.started|updated|completed {item}` with item types `agent_message`,
//!   `reasoning`, `command_execution {exit_code, status}`, `file_change
//!   {status}`, `mcp_tool_call {tool, status}`, `web_search`, `todo_list`,
//!   `error`; and top-level `error {message}`.
//!
//! Verified on 2026-11-01 with the installed `codex` 0.159.2 against a local
//! fake Responses server (no provider; fixture
//! `tests/fixtures/codex/recorded_fake_gateway.jsonl`): the generated
//! `config.toml` loads under `--strict-config` (which rejects unknown keys),
//! the only request is `POST <base_url>/responses` with
//! `Authorization: Bearer <$env_key>`, Codex sends `prompt_cache_key` itself,
//! and the stream is the shape parsed here. Warnings arrive as
//! `item.completed` items of type `error` (e.g. "Model metadata for
//! `openai/gpt-5` not found"), which become `error` events, not failures.
//!
//! Pinning: the gateway must speak the Responses API (`/v1/responses`;
//! LiteLLM does). The key is read by Codex from `env_key = <key_env>`;
//! `shell_environment_policy.inherit = "core"` keeps it out of the commands
//! the agent runs. `sandbox_mode = "workspace-write"` keeps Codex's own
//! command sandbox on as defense in depth inside the container (whether its
//! Landlock/seccomp sandbox works under gVisor is unverified; the container
//! is the boundary either way).

use crate::clock::Clock;
use crate::driver::{ProcessAdapter, process_runtime};
use crate::endpoint::GatewayEndpoint;
use crate::events::{EventLog, Parsed, result, str_at, u64_at};
use crate::invocation::Invocation;
use crate::prompt;
use guard_core::ports::agent::{AgentTask, RuntimeError, RuntimeEventKind, TaskStatus, Usage};
use guard_core::ports::sandbox::{ExecOutput, Sandbox, SandboxProvider, WORKSPACE_DIR};
use serde_json::Value;
use std::fmt::Write as _;

pub const NAME: &str = "codex";
pub const CODEX_HOME: &str = "/task/codex";
pub const CONFIG_PATH: &str = "/task/codex/config.toml";
pub const PROVIDER_ID: &str = "guard_gateway";

pub fn invocation(task: &AgentTask) -> Result<Invocation, RuntimeError> {
    let ep = GatewayEndpoint::pin(&task.gateway)?;
    let argv = [
        "codex",
        "exec",
        "--json",
        "--strict-config",
        "--ephemeral",
        "--skip-git-repo-check",
        "--cd",
        WORKSPACE_DIR,
        "-",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    let mut inv = Invocation::new(argv)
        .with_env("CODEX_HOME", CODEX_HOME)
        .with_file(CONFIG_PATH, config_toml(task, &ep));
    inv.stdin = Some(prompt::render(task));
    Ok(inv)
}

/// A TOML basic string (JSON string escapes are a subset of TOML's).
fn q(s: &str) -> String {
    serde_json::to_string(s).expect("string")
}

fn config_toml(task: &AgentTask, ep: &GatewayEndpoint) -> String {
    let mut c = String::new();
    c.push_str("# Generated by guard-runtimes for one task; do not edit.\n");
    let _ = writeln!(c, "model = {}", q(&task.model));
    let _ = writeln!(c, "model_provider = {}", q(PROVIDER_ID));
    c.push_str("approval_policy = \"never\"\n");
    c.push_str("sandbox_mode = \"workspace-write\"\n");
    c.push_str("web_search = \"disabled\"\n");
    c.push_str("check_for_update_on_startup = false\n");
    c.push_str("\n[analytics]\nenabled = false\n");
    c.push_str("\n[feedback]\nenabled = false\n");
    c.push_str("\n[history]\npersistence = \"none\"\n");
    c.push_str("\n[shell_environment_policy]\ninherit = \"core\"\n");
    c.push_str(
        "\n[sandbox_workspace_write]\nwritable_roots = [\"/task\"]\nnetwork_access = false\n",
    );
    let _ = write!(
        c,
        "\n[model_providers.{PROVIDER_ID}]\nname = \"guard gateway\"\nbase_url = {}\nenv_key = {}\nwire_api = \"responses\"\n",
        q(&ep.v1()),
        q(&task.gateway.key_env)
    );
    if !task.tools.is_empty() {
        let tools: Vec<String> = task.tools.iter().map(|t| q(t)).collect();
        let _ = write!(
            c,
            "\n[mcp_servers.guard]\ncommand = \"guard\"\nargs = [\"mcp\"]\nenabled_tools = [{}]\n",
            tools.join(", ")
        );
    }
    c
}

/// Parses `codex exec --json` stdout. `model` labels the `model_call`
/// events (the stream does not name the model).
pub fn parse_jsonl(stdout: &[u8], model: &str, clock: &dyn Clock) -> Parsed {
    let text = String::from_utf8_lossy(stdout);
    let mut log = EventLog::default();
    let mut last_message = String::new();
    let mut turns = 0u32;
    let mut failure: Option<String> = None;
    let mut completed = false;
    for line in text.lines().filter(|l| !l.trim().is_empty()) {
        let now = clock.now_millis();
        let Ok(v) = serde_json::from_str::<Value>(line) else {
            log.push_at(
                now,
                RuntimeEventKind::Error {
                    message: format!("codex event line is not JSON: {}", line.trim()),
                },
            );
            continue;
        };
        match str_at(&v, "type") {
            Some("item.completed") => {
                let item = &v["item"];
                let status_ok = str_at(item, "status") == Some("completed");
                let tool = |name: &str, ok: bool| RuntimeEventKind::ToolCall {
                    tool: name.to_string(),
                    ok,
                    duration_ms: 0,
                };
                match str_at(item, "type") {
                    Some("command_execution") => {
                        let ok =
                            status_ok && item.get("exit_code").and_then(Value::as_i64) == Some(0);
                        log.push_at(now, tool("shell", ok));
                    }
                    Some("file_change") => log.push_at(now, tool("apply_patch", status_ok)),
                    Some("mcp_tool_call") => {
                        let name = str_at(item, "tool").unwrap_or("unknown");
                        log.push_at(now, tool(name, status_ok));
                    }
                    Some("web_search") => log.push_at(now, tool("web_search", true)),
                    Some("agent_message") => {
                        let t = str_at(item, "text").unwrap_or_default();
                        last_message = t.to_string();
                        log.push_at(now, RuntimeEventKind::Message { text: t.into() });
                    }
                    Some("error") => log.push_at(
                        now,
                        RuntimeEventKind::Error {
                            message: str_at(item, "message").unwrap_or_default().into(),
                        },
                    ),
                    _ => {}
                }
            }
            Some("turn.completed") => {
                turns += 1;
                completed = true;
                let u = &v["usage"];
                log.push_at(
                    now,
                    RuntimeEventKind::ModelCall {
                        model: model.to_string(),
                        usage: Usage {
                            input_tokens: u64_at(u, "input_tokens"),
                            output_tokens: u64_at(u, "output_tokens"),
                            cached_input_tokens: u64_at(u, "cached_input_tokens"),
                            cache_creation_input_tokens: u64_at(u, "cache_write_input_tokens"),
                        },
                        cost_usd: 0.0,
                    },
                );
            }
            Some("turn.failed") => {
                turns += 1;
                let m = str_at(&v["error"], "message")
                    .unwrap_or("turn failed")
                    .to_string();
                log.push_at(now, RuntimeEventKind::Error { message: m.clone() });
                failure = Some(m);
            }
            Some("error") => log.push_at(
                now,
                RuntimeEventKind::Error {
                    message: str_at(&v, "message").unwrap_or_default().into(),
                },
            ),
            _ => {}
        }
    }
    let result = if let Some(err) = failure {
        Some(result(
            if is_budget_rejection(&err) {
                TaskStatus::BudgetExceeded
            } else {
                TaskStatus::Failed
            },
            &last_message,
            log.usage_sum(),
            0.0,
            turns,
            Some(err),
        ))
    } else if completed {
        Some(result(
            TaskStatus::Completed,
            &last_message,
            log.usage_sum(),
            0.0,
            turns,
            None,
        ))
    } else {
        None
    };
    Parsed {
        events: log.into_events(),
        result,
    }
}

/// Codex has no budget flag: the virtual key's `max_budget` is its only
/// limit, and the gateway reports exhaustion as LiteLLM's `budget_exceeded`
/// error ("Budget has been exceeded! ...").
fn is_budget_rejection(message: &str) -> bool {
    let m = message.to_ascii_lowercase();
    m.contains("budget_exceeded") || m.contains("budget has been exceeded")
}

process_runtime!(
    /// `AgentRuntime` for Codex CLI (`codex exec --json`).
    CodexRuntime
);

#[async_trait::async_trait]
impl ProcessAdapter for CodexRuntime {
    fn name(&self) -> &'static str {
        NAME
    }

    fn invocation(&self, task: &AgentTask) -> Result<Invocation, RuntimeError> {
        invocation(task)
    }

    async fn collect(
        &self,
        _provider: &dyn SandboxProvider,
        _sandbox: &Sandbox,
        task: &AgentTask,
        output: &ExecOutput,
        clock: &dyn Clock,
    ) -> Result<Parsed, RuntimeError> {
        Ok(parse_jsonl(&output.stdout, &task.model, clock))
    }
}
