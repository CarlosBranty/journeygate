//! `guard agents sync`: one source of skills and conventions, rendered once
//! per runtime (architecture section 16).
//!
//! Source (repo root): `agents/AGENTS.md` and `agents/skills/<name>/SKILL.md`
//! (YAML frontmatter `name` = directory name, `description` starting with
//! "Use when"). Outputs, relative to the repo root:
//!
//! | Runtime | Developer assistant files | Sandbox mount (`/agents`) |
//! | --- | --- | --- |
//! | `claude-code` | `.claude/skills/<name>/SKILL.md`, `CLAUDE.md` block (`@AGENTS.md`), `AGENTS.md` block, `.mcp.json` `mcpServers.guard` | `.guard/agents/rendered/claude-code/` |
//! | `codex` | `AGENTS.md` block, `.guard/agents/mcp/codex.toml` snippet | `.guard/agents/rendered/codex/` |
//! | `copilot-cli` | `.github/copilot-instructions.md` block, `.guard/agents/mcp/copilot-cli.json` snippet | `.guard/agents/rendered/copilot-cli/` |
//! | other runtimes | — | `.guard/agents/rendered/<runtime>/` |
//!
//! Ownership: files under `.guard/agents/` and generated `.claude/skills/*`
//! (marked with [`GENERATED_MARKER`]) are owned by sync and removed when no
//! longer rendered. Shared files (`AGENTS.md`, `CLAUDE.md`,
//! `.github/copilot-instructions.md`) only get a block between
//! [`BLOCK_BEGIN`] and [`BLOCK_END`]; text outside it is the user's.
//! `.mcp.json` only gets its `mcpServers.guard` entry. Rendering is
//! deterministic and idempotent; `check` computes the same plan and writes
//! nothing (CI). Line endings are compared modulo CRLF so a Windows
//! checkout with `core.autocrlf` is not drift.

use crate::config::RuntimeKind;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

pub const BLOCK_BEGIN: &str = "<!-- guard:agents:begin (generated by `guard agents sync` from agents/; edit the source, not this block) -->";
pub const BLOCK_END: &str = "<!-- guard:agents:end -->";
/// Present in every file sync owns outright.
pub const GENERATED_MARKER: &str = "generated by `guard agents sync`";
/// The stdio MCP server every assistant registers.
pub const MCP_COMMAND: &str = "guard";
pub const MCP_ARGS: &[&str] = &["mcp"];

const SOURCE_DIR: &str = "agents";
const RENDERED_DIR: &str = ".guard/agents/rendered";
const MCP_SNIPPETS_DIR: &str = ".guard/agents/mcp";
const CLAUDE_SKILLS_DIR: &str = ".claude/skills";
const MAX_DESCRIPTION: usize = 1024;

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum SyncError {
    /// Missing or malformed `agents/` source.
    #[error("agents source: {0}")]
    Source(String),
    /// An existing file sync must merge into cannot be parsed; nothing was written.
    #[error("cannot merge into {0}")]
    Conflict(String),
    #[error("io: {0}")]
    Io(String),
}

fn io(path: &Path) -> impl FnOnce(std::io::Error) -> SyncError + '_ {
    move |e| SyncError::Io(format!("{}: {e}", path.display()))
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyncOptions {
    /// Runtimes to render (normally `AgentsConfig::runtimes_in_use()` plus
    /// the developer's assistants).
    pub runtimes: BTreeSet<RuntimeKind>,
    /// Compute the plan, write nothing.
    pub check: bool,
}

/// Repo-relative `/`-separated paths, sorted.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct SyncReport {
    /// Created or changed (or, with `check`, that would be).
    pub written: Vec<String>,
    /// Owned files no longer rendered (or that would be removed).
    pub removed: Vec<String>,
    pub unchanged: Vec<String>,
}

impl SyncReport {
    /// Nothing to write or remove: `--check` passes.
    pub fn is_clean(&self) -> bool {
        self.written.is_empty() && self.removed.is_empty()
    }
}

