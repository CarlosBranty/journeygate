#[derive(Debug, Clone, PartialEq, Eq)]
enum Part {
    /// The whole file belongs to sync.
    Owned(String),
    /// A managed block inside a shared file.
    Block(String),
    /// `mcpServers.guard` inside a JSON object.
    McpServer(serde_json::Value),
}

fn header_md(source: &str) -> String {
    format!("<!-- {GENERATED_MARKER} from {source}; edit the source -->\n")
}

fn mcp_entry() -> serde_json::Value {
    serde_json::json!({ "command": MCP_COMMAND, "args": MCP_ARGS })
}

/// The `guard mcp` registration of each runtime that has one.
fn mcp_plan(runtimes: &BTreeSet<RuntimeKind>) -> BTreeMap<String, Part> {
    let mut files = BTreeMap::new();
    if runtimes.contains(&RuntimeKind::ClaudeCode) {
        files.insert(".mcp.json".into(), Part::McpServer(mcp_entry()));
    }
    if runtimes.contains(&RuntimeKind::Codex) {
        files.insert(
            format!("{MCP_SNIPPETS_DIR}/codex.toml"),
            Part::Owned(format!(
                "# {GENERATED_MARKER}. Add to ~/.codex/config.toml (or a trusted project's .codex/config.toml).\n\
                 [mcp_servers.guard]\ncommand = \"{MCP_COMMAND}\"\nargs = [{}]\n",
                MCP_ARGS
                    .iter()
                    .map(|a| format!("\"{a}\""))
                    .collect::<Vec<_>>()
                    .join(", ")
            )),
        );
    }
    if runtimes.contains(&RuntimeKind::CopilotCli) {
        let snippet = serde_json::json!({
            "mcpServers": {
                "guard": {
                    "type": "local",
                    "command": MCP_COMMAND,
                    "args": MCP_ARGS,
                    "tools": ["*"]
                }
            }
        });
        files.insert(
            format!("{MCP_SNIPPETS_DIR}/copilot-cli.json"),
            Part::Owned(pretty(&snippet)),
        );
    }
    files
}

/// Runtimes that have a `guard mcp` registration ([`sync_mcp`] renders one).
pub const MCP_RUNTIMES: [RuntimeKind; 3] = [
    RuntimeKind::ClaudeCode,
    RuntimeKind::Codex,
    RuntimeKind::CopilotCli,
];

fn plan(source: &Source, runtimes: &BTreeSet<RuntimeKind>) -> BTreeMap<String, Part> {
    let mut files = BTreeMap::new();
    let repo_conventions = source.conventions("agents/skills");
    let claude = runtimes.contains(&RuntimeKind::ClaudeCode);
    if claude || runtimes.contains(&RuntimeKind::Codex) {
        files.insert("AGENTS.md".into(), Part::Block(repo_conventions.clone()));
    }
    if claude {
        for k in &source.skills {
            files.insert(
                format!("{CLAUDE_SKILLS_DIR}/{}/SKILL.md", k.name),
                Part::Owned(k.rendered()),
            );
        }
        files.insert(
            "CLAUDE.md".into(),
            Part::Block(
                "Project conventions and the skills index live in AGENTS.md:\n\n@AGENTS.md\n"
                    .into(),
            ),
        );
    }
    if runtimes.contains(&RuntimeKind::CopilotCli) {
        files.insert(
            ".github/copilot-instructions.md".into(),
            Part::Block(repo_conventions),
        );
    }
    files.extend(mcp_plan(runtimes));
    // Sandbox mounts: one read-only directory per runtime at /agents.
    let sandbox_conventions = format!(
        "{}{}",
        header_md("agents/AGENTS.md"),
        source.conventions("/agents/skills")
    );
    for rt in runtimes {
        let base = format!("{RENDERED_DIR}/{}", rt.as_str());
        files.insert(
            format!("{base}/AGENTS.md"),
            Part::Owned(sandbox_conventions.clone()),
        );
        for k in &source.skills {
            files.insert(
                format!("{base}/skills/{}/SKILL.md", k.name),
                Part::Owned(k.rendered()),
            );
        }
        match rt {
            RuntimeKind::ClaudeCode => {
                files.insert(
                    format!("{base}/CLAUDE.md"),
                    Part::Owned(format!("{}@AGENTS.md\n", header_md("agents/AGENTS.md"))),
                );
            }
            RuntimeKind::CopilotCli => {
                files.insert(
                    format!("{base}/copilot-instructions.md"),
                    Part::Owned(sandbox_conventions.clone()),
                );
            }
            _ => {}
        }
    }
    files
}

fn pretty(v: &serde_json::Value) -> String {
    let mut s = serde_json::to_string_pretty(v).expect("json values always serialize");
    s.push('\n');
    s
}

/// The new content of a shared file with `block` upserted.
fn upsert_block(existing: Option<&str>, block: &str) -> String {
    let managed = format!("{BLOCK_BEGIN}\n{block}{BLOCK_END}\n");
    let Some(existing) = existing.map(lf).filter(|e| !e.trim().is_empty()) else {
        return managed;
    };
    if let (Some(b), Some(e)) = (existing.find(BLOCK_BEGIN), existing.find(BLOCK_END)) {
        if b < e {
            let mut end = e + BLOCK_END.len();
            if existing[end..].starts_with('\n') {
                end += 1;
            }
            return format!("{}{managed}{}", &existing[..b], &existing[end..]);
        }
    }
    format!("{}\n{managed}", with_final_newline(&existing))
}

fn merge_mcp(
    path: &str,
    existing: Option<&str>,
    entry: &serde_json::Value,
) -> Result<String, SyncError> {
    let mut doc = match existing.filter(|e| !e.trim().is_empty()) {
        None => serde_json::json!({}),
        Some(text) => serde_json::from_str::<serde_json::Value>(text)
            .ok()
            .filter(|v| v.is_object())
            .ok_or_else(|| SyncError::Conflict(format!("{path}: not a JSON object")))?,
    };
    let servers = doc
        .as_object_mut()
        .expect("checked object")
        .entry("mcpServers")
        .or_insert_with(|| serde_json::json!({}));
    let servers = servers
        .as_object_mut()
        .ok_or_else(|| SyncError::Conflict(format!("{path}: mcpServers is not an object")))?;
    servers.insert("guard".into(), entry.clone());
    Ok(pretty(&doc))
}

fn read_opt(path: &Path) -> Result<Option<String>, SyncError> {
    match fs::read_to_string(path) {
        Ok(s) => Ok(Some(s)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(SyncError::Io(format!("{}: {e}", path.display()))),
    }
}

/// Owned files currently on disk: everything under `.guard/agents/{rendered,mcp}`
/// and generated `.claude/skills/*/SKILL.md`.
fn owned_on_disk(root: &Path) -> Result<BTreeSet<String>, SyncError> {
    fn walk(root: &Path, dir: &Path, out: &mut BTreeSet<String>) -> Result<(), SyncError> {
        if !dir.is_dir() {
            return Ok(());
        }
        for entry in fs::read_dir(dir).map_err(io(dir))? {
            let p = entry.map_err(io(dir))?.path();
            if p.is_dir() {
                walk(root, &p, out)?;
            } else {
                out.insert(rel(root, &p));
            }
        }
        Ok(())
    }
    let mut out = BTreeSet::new();
    walk(root, &root.join(RENDERED_DIR), &mut out)?;
    walk(root, &root.join(MCP_SNIPPETS_DIR), &mut out)?;
    let skills = root.join(CLAUDE_SKILLS_DIR);
    if skills.is_dir() {
        for entry in fs::read_dir(&skills).map_err(io(&skills))? {
            let f = entry.map_err(io(&skills))?.path().join("SKILL.md");
            if read_opt(&f)?.is_some_and(|s| s.contains(GENERATED_MARKER)) {
                out.insert(rel(root, &f));
            }
        }
    }
    Ok(out)
}

fn rel(root: &Path, p: &Path) -> String {
    p.strip_prefix(root)
        .unwrap_or(p)
        .to_string_lossy()
        .replace('\\', "/")
}

/// Removes `path` and then its empty parents up to (not including) `stop`.
fn remove_with_empty_parents(path: &Path, stop: &Path) -> Result<(), SyncError> {
    fs::remove_file(path).map_err(io(path))?;
    let mut dir: Option<PathBuf> = path.parent().map(Path::to_path_buf);
    while let Some(d) = dir {
        if d == stop || !d.starts_with(stop) {
            break;
        }
        let empty = fs::read_dir(&d).map_err(io(&d))?.next().is_none();
        if !empty {
            break;
        }
        fs::remove_dir(&d).map_err(io(&d))?;
        dir = d.parent().map(Path::to_path_buf);
    }
    Ok(())
}

/// Renders `<repo_root>/agents/` for `options.runtimes` (see the module docs).
pub fn sync(repo_root: &Path, options: &SyncOptions) -> Result<SyncReport, SyncError> {
    let source = Source::load(&repo_root.join(SOURCE_DIR))?;
    let files = plan(&source, &options.runtimes);
    let (mut report, changes) = diff(repo_root, &files)?;
    let stale: Vec<String> = owned_on_disk(repo_root)?
        .into_iter()
        .filter(|p| !files.contains_key(p))
        .collect();
    report.removed = stale.clone();

    if !options.check {
        write_changes(repo_root, &changes)?;
        for path in &stale {
            remove_with_empty_parents(&repo_root.join(path), repo_root)?;
        }
    }
    Ok(report)
}

/// Only the MCP part of [`sync`]: the `guard mcp` registration of each of
/// `runtimes` (`guard init --mcp`). Needs no `agents/` source, removes
/// nothing, and merges `.mcp.json` the same way (other servers are kept).
pub fn sync_mcp(
    repo_root: &Path,
    runtimes: &BTreeSet<RuntimeKind>,
    check: bool,
) -> Result<SyncReport, SyncError> {
    let (report, changes) = diff(repo_root, &mcp_plan(runtimes))?;
    if !check {
        write_changes(repo_root, &changes)?;
    }
    Ok(report)
}

type Changes = Vec<(String, String)>;

/// The new content of every planned file that differs from disk. Computed
/// before any write, so a conflict aborts with nothing written.
fn diff(
    repo_root: &Path,
    files: &BTreeMap<String, Part>,
) -> Result<(SyncReport, Changes), SyncError> {
    let mut changes: Changes = Vec::new();
    let mut report = SyncReport::default();
    for (path, part) in files {
        let abs = repo_root.join(path);
        let existing = read_opt(&abs)?;
        let new = match part {
            Part::Owned(content) => content.clone(),
            Part::Block(block) => upsert_block(existing.as_deref(), block),
            Part::McpServer(entry) => merge_mcp(path, existing.as_deref(), entry)?,
        };
        let same = match (&existing, part) {
            (Some(old), Part::McpServer(_)) => {
                serde_json::from_str::<serde_json::Value>(old).ok()
                    == serde_json::from_str::<serde_json::Value>(&new).ok()
            }
            (Some(old), _) => lf(old) == new,
            (None, _) => false,
        };
        if same {
            report.unchanged.push(path.clone());
        } else {
            report.written.push(path.clone());
            changes.push((path.clone(), new));
        }
    }
    Ok((report, changes))
}

fn write_changes(repo_root: &Path, changes: &Changes) -> Result<(), SyncError> {
    for (path, content) in changes {
        let abs = repo_root.join(path);
        if let Some(parent) = abs.parent() {
            fs::create_dir_all(parent).map_err(io(parent))?;
        }
        fs::write(&abs, content).map_err(io(&abs))?;
    }
    Ok(())
}
